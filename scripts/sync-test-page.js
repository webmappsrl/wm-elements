#!/usr/bin/env node
// Copies the <link>/<script> tags Angular generates in dist/<widget>/index.html
// (runtime/polyfills/scripts/main bundles, all hashed and renamed on every build)
// into every test/<widget>/*.html page that has the bundle markers, so the manual
// test pages always reference the bundles that actually exist on disk instead of
// a stale hardcoded filename.
//
// Usage: node scripts/sync-test-page.js <widget-name>
// Each widget in this repo gets its own dist/<widget>/ build output (see
// angular.json build configurations) and its own test/<widget>/ pages —
// this keeps widgets independently buildable/publishable as the repo grows.
const fs = require('fs');
const path = require('path');

const widget = process.argv[2];
if (!widget) {
  console.error('Usage: node scripts/sync-test-page.js <widget-name>');
  process.exit(1);
}

const root = path.resolve(__dirname, '..');
const distIndexPath = path.join(root, `dist/${widget}/index.html`);
const testDir = path.join(root, `test/${widget}`);

if (!fs.existsSync(distIndexPath)) {
  console.error(`Not found: ${distIndexPath} — run "npm run build:${widget}" first.`);
  process.exit(1);
}
if (!fs.existsSync(testDir)) {
  console.error(`Not found: ${testDir} — create it first (see test/wm-layer-map/index.html as a template).`);
  process.exit(1);
}

const distHtml = fs.readFileSync(distIndexPath, 'utf8');
const tags = [...distHtml.matchAll(/<link[^>]*>|<script[^>]*>(?:<\/script>)?/g)]
  .map(m => (m[0].startsWith('<script') && !m[0].endsWith('</script>') ? `${m[0]}</script>` : m[0]))
  .filter(tag => !/rel="icon"/.test(tag))
  // dist/<widget>/index.html references bundles relative to its own folder;
  // test/<widget>/index.html is a sibling folder under test/, so point back
  // through ../../dist/<widget>/.
  .map(tag => tag.replace(/(href|src)="(?!https?:\/\/)([^"]+)"/, `$1="../../dist/${widget}/$2"`));

const bundleBlock = `  <!-- Generated by scripts/sync-test-page.js — do not edit by hand, re-run "npm run build:test:${widget}" -->\n  ${tags.join('\n  ')}\n`;

const markerPattern = /<!-- BEGIN bundle tags -->[\s\S]*?<!-- END bundle tags -->/;

// Ogni pagina HTML di test/<widget>/ con i marker viene aggiornata: alcuni
// scenari stanno in pagine separate (es. track-id.html, oc:8937) perché le
// istanze di una stessa pagina condividono lo store.
const updatedPages = fs
  .readdirSync(testDir)
  .filter(name => name.endsWith('.html'))
  .filter(name => {
    const pagePath = path.join(testDir, name);
    const testHtml = fs.readFileSync(pagePath, 'utf8');
    if (!markerPattern.test(testHtml)) {
      return false;
    }
    const updated = testHtml.replace(
      markerPattern,
      `<!-- BEGIN bundle tags -->\n${bundleBlock}  <!-- END bundle tags -->`,
    );
    fs.writeFileSync(pagePath, updated);
    return true;
  });

if (updatedPages.length === 0) {
  console.error(`Could not find "<!-- BEGIN bundle tags -->" / "<!-- END bundle tags -->" markers in any page of test/${widget}/.`);
  process.exit(1);
}

console.log(
  `test/${widget}/{${updatedPages.join(', ')}} updated with ${tags.length} bundle tag(s) from dist/${widget}/index.html.`,
);
